import assert from 'node:assert/strict';
import {Marked} from 'marked';
import {createMarkdown} from '../web/markdown.mjs';
const escape=s=>s.replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const render=createMarkdown(Marked,html=>html,escape);
const range='광도가 태양의 수십~수천 배인 거성, 수만~수십만 배인 초거성';
assert.equal(render(range),`<p>${range}</p>\n`);
assert.equal(render('20~60초, 3~5장'),'<p>20~60초, 3~5장</p>\n');
assert.equal(render('~~잘못된 판단~~'),'<p><del>잘못된 판단</del></p>\n');
assert.equal(render('`x~y` 와 **비교 기준**'),'<p><code>x~y</code> 와 <strong>비교 기준</strong></p>\n');
assert.ok(render('```text\na~b~c\n```').includes('a~b~c'));
assert.ok(render('$a \\sim b$ 와 $x<y$').includes('$a \\sim b$ 와 $x&lt;y$'));
assert.ok(render('| 조건 | 판단 |\n| --- | --- |\n| A | B |').includes('<table>'));
assert.ok(render('<보기>를 읽는다.').includes('&lt;보기&gt;'));
assert.ok(render('[노트](#/read/math-cubic)').includes('href="#/read/math-cubic"'));
let sanitized=false;
createMarkdown(Marked,html=>{sanitized=true;return html;},escape)('**내용**');
assert.equal(sanitized,true);
console.log('Markdown ranges, deliberate deletion, code, math, tables and sanitizer passed.');
